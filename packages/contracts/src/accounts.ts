import { InstantSchema, UuidSchema } from './auth.js';
import {
  ColorSchema,
  CurrencyCodeSchema,
  DecimalStringSchema,
  EntityNameSchema,
  IconKeySchema,
  LocalDateSchema,
} from './common.js';
import { z } from './zod.js';

// Accounts (data-model.md#accounts, features.md#accounts). Stage 3 has no balances: the opening
// balance is the only amount.

export const ACCOUNT_KINDS = [
  'BANK',
  'CASH',
  'SAVINGS',
  'CREDIT_CARD',
  'E_WALLET',
  'OTHER',
  'CUSTOM',
] as const;
export const AccountKindSchema = z.enum(ACCOUNT_KINDS).openapi('AccountKind');
export type AccountKind = z.infer<typeof AccountKindSchema>;

export const CustomKindLabelSchema = z.string().trim().min(1).max(50);

export const AccountSchema = z
  .object({
    id: UuidSchema,
    name: z.string(),
    currency: z.string(),
    kind: AccountKindSchema,
    customKindLabel: z.string().nullable(),
    icon: z.string(),
    color: z.string(),
    /** Account currency, formatted at the currency exponent. */
    openingBalance: z.string(),
    openingDate: LocalDateSchema,
    includeInNetWorthWidget: z.boolean(),
    sortOrder: z.number().int(),
    archivedAt: InstantSchema.nullable(),
    version: z.number().int(),
    createdAt: InstantSchema,
    updatedAt: InstantSchema,
  })
  .openapi('Account');

export const AccountListResponseSchema = z
  .object({ items: z.array(AccountSchema) })
  .openapi('AccountListResponse');

const customLabelMatchesKind = (value: {
  kind?: AccountKind | undefined;
  customKindLabel?: string | null | undefined;
}) => {
  if (value.kind === undefined) return true;
  const hasLabel = value.customKindLabel !== undefined && value.customKindLabel !== null;
  return value.kind === 'CUSTOM' ? hasLabel : !hasLabel;
};
const CUSTOM_LABEL_RULE = {
  message: 'customKindLabel is required for kind CUSTOM and not allowed otherwise',
  path: ['customKindLabel'],
};

export const AccountCreateSchema = z
  .strictObject({
    /** Client-generated id (offline-first); generated by the server when omitted. */
    id: UuidSchema.optional(),
    name: EntityNameSchema,
    currency: CurrencyCodeSchema,
    kind: AccountKindSchema,
    customKindLabel: CustomKindLabelSchema.nullable().optional(),
    icon: IconKeySchema,
    color: ColorSchema,
    /** Must not have more fraction digits than the currency exponent (`AMOUNT_PRECISION`). */
    openingBalance: DecimalStringSchema.default('0'),
    openingDate: LocalDateSchema,
    includeInNetWorthWidget: z.boolean().default(true),
    /** Appended at the end when omitted. */
    sortOrder: z.number().int().min(0).max(1_000_000).optional(),
  })
  .refine(customLabelMatchesKind, CUSTOM_LABEL_RULE)
  .openapi('AccountCreate');

/**
 * Partial update. Changing `kind` away from `CUSTOM` must clear `customKindLabel` (send null);
 * the server checks the rule against the merged result.
 */
export const AccountUpdateSchema = z
  .strictObject({
    name: EntityNameSchema.optional(),
    /** Editable while the account has no postings (always in Stage 3). */
    currency: CurrencyCodeSchema.optional(),
    kind: AccountKindSchema.optional(),
    customKindLabel: CustomKindLabelSchema.nullable().optional(),
    icon: IconKeySchema.optional(),
    color: ColorSchema.optional(),
    openingBalance: DecimalStringSchema.optional(),
    openingDate: LocalDateSchema.optional(),
    includeInNetWorthWidget: z.boolean().optional(),
    sortOrder: z.number().int().min(0).max(1_000_000).optional(),
    /** Alternative to `If-Match`. */
    version: z.number().int().min(1).optional(),
  })
  .openapi('AccountUpdate');

export type Account = z.infer<typeof AccountSchema>;
export type AccountListResponse = z.infer<typeof AccountListResponseSchema>;
export type AccountCreate = z.input<typeof AccountCreateSchema>;
export type AccountCreateParsed = z.output<typeof AccountCreateSchema>;
export type AccountUpdate = z.infer<typeof AccountUpdateSchema>;

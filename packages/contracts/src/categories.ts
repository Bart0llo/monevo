import { InstantSchema, UuidSchema } from './auth.js';
import { ColorSchema, EntityNameSchema, IconKeySchema } from './common.js';
import { z } from './zod.js';

// Categories (data-model.md#categories, features.md#categories). Two levels: a top-level category
// and its subcategories. A subcategory has the type of its parent. An archived parent hides its
// children; children keep their own `archivedAt`.

export const CATEGORY_TYPES = ['INCOME', 'EXPENSE'] as const;
export const CategoryTypeSchema = z.enum(CATEGORY_TYPES).openapi('CategoryType');
export type CategoryType = z.infer<typeof CategoryTypeSchema>;

/** Maximum depth: top level (1) and subcategory (2). */
export const CATEGORY_MAX_DEPTH = 2;

export const CategorySchema = z
  .object({
    id: UuidSchema,
    name: z.string(),
    type: CategoryTypeSchema,
    parentId: UuidSchema.nullable(),
    icon: z.string(),
    color: z.string(),
    sortOrder: z.number().int(),
    archivedAt: InstantSchema.nullable(),
    version: z.number().int(),
    createdAt: InstantSchema,
    updatedAt: InstantSchema,
  })
  .openapi('Category');

export const CategoryListResponseSchema = z
  .object({ items: z.array(CategorySchema) })
  .openapi('CategoryListResponse');

export const CategoryCreateSchema = z
  .strictObject({
    /** Client-generated id (offline-first); generated by the server when omitted. */
    id: UuidSchema.optional(),
    name: EntityNameSchema,
    type: CategoryTypeSchema,
    /** A top-level, non-archived category of the same type. */
    parentId: UuidSchema.optional(),
    icon: IconKeySchema,
    color: ColorSchema,
    /** Appended at the end of its siblings when omitted. */
    sortOrder: z.number().int().min(0).max(1_000_000).optional(),
  })
  .openapi('CategoryCreate');

export const CategoryUpdateSchema = z
  .strictObject({
    name: EntityNameSchema.optional(),
    /** Not allowed for a category with subcategories (`CATEGORY_TYPE_MISMATCH`). */
    type: CategoryTypeSchema.optional(),
    /** Null promotes a subcategory to the top level. */
    parentId: UuidSchema.nullable().optional(),
    icon: IconKeySchema.optional(),
    color: ColorSchema.optional(),
    /** Alternative to `If-Match`. */
    version: z.number().int().min(1).optional(),
  })
  .openapi('CategoryUpdate');

/** Sets `sortOrder = index` for siblings (same parent and type). */
export const CategoryReorderSchema = z
  .strictObject({
    ids: z
      .array(UuidSchema)
      .min(1)
      .max(500)
      .refine((ids) => new Set(ids).size === ids.length, { message: 'Ids must be unique' }),
  })
  .openapi('CategoryReorder');

export type Category = z.infer<typeof CategorySchema>;
export type CategoryListResponse = z.infer<typeof CategoryListResponseSchema>;
export type CategoryCreate = z.infer<typeof CategoryCreateSchema>;
export type CategoryUpdate = z.infer<typeof CategoryUpdateSchema>;
export type CategoryReorder = z.infer<typeof CategoryReorderSchema>;
